use russell_lab::{Matrix, approx_eq};
use russell_tensor::{SQRT_2, StrError, Tensor3};

// Expected output
// ┌                                                 ┐
// │ -0.5847  0.5429  0.4375  0.1041 -0.0495 -0.4892 │
// │  0.0572  0.3270 -0.2430  0.2447  0.9378 -0.0905 │
// │  0.0671 -0.3796 -0.1829 -0.1587  0.0087  0.0285 │
// └                                                 ┘

fn main() -> Result<(), StrError> {
    // Material: mp-632480 (Ag3SI)
    // Symmetry: P1 (Space Group 1)
    #[rustfmt::skip]
    let e = Tensor3::<3, 6>::from_std_array(&[[
        [-0.58469404,  0.0736221,  -0.34594367],
        [ 0.0736221,   0.54292064, -0.03498525],
        [-0.34594367, -0.03498525,  0.43751018],
    ], [
        [ 0.05722553,  0.17305302, -0.06398525],
        [ 0.17305302,  0.32695506,  0.66311367],
        [-0.06398525,  0.66311367, -0.2430092],
    ], [
        [ 0.06706598, -0.11224779,  0.02014558],
        [-0.11224779, -0.37956598,  0.00614898],
        [ 0.02014558,  0.00614898, -0.18289   ],
    ]])?;
    println!("{:.4}", e);

    // original Voigt matrix
    #[rustfmt::skip]
    let voigt = [
        [ -0.5846940358861791,  0.542920642554744,  0.43751018171792405, -0.034985246664449, -0.34594366745860705, 0.073622103782504 ],
        [ 0.057225533339327006, 0.326955057151104, -0.24300919672545102,  0.663113667458608, -0.063985246664449,   0.173053022212409 ],
        [ 0.067065980085643,   -0.379565980085643, -0.18289000000000002,  0.006148980319727,  0.020145583660633,  -0.11224778856792  ],
    ];

    // convert Voigt matrix to Kelvin-Mandel matrix
    // Kelvin-Mandel: 3:01, 4:12, 5:02
    // Voigt:         5:01, 3:12, 4:02
    let mut kel = Matrix::new(3, 6);
    for m in 0..3 {
        for n in 0..3 {
            kel[(m, n)] = voigt[m][n];
        }
        kel[(m, 3)] = SQRT_2 * voigt[m][5];
        kel[(m, 4)] = SQRT_2 * voigt[m][3];
        kel[(m, 5)] = SQRT_2 * voigt[m][4];
    }

    // check
    for m in 0..3 {
        for n in 0..6 {
            approx_eq(e.get(m, n), kel[(m, n)], 1e-8);
        }
    }

    Ok(())
}
